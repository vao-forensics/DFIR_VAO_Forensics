#!/usr/bin/env python3
"""Write the local LLM stack for install.sh: llama-swap config.yaml + docker-compose.yml.

  gen_llm_stack.py PROFILE GPU_COUNT GPU_MIN_GB MODELS_DIR OUT_DIR [ROUTER_APP_DIR]

PROFILE small|medium|large = local GPUs; router = no local LLM: llm-router (installer/llm_router)
serves the bot's names from another server or a cloud provider (OUT_DIR/router.json).

Every model name the bot asks for (gpt-small-20b, reasoner-31b, reasoner-31b-b, agent-30b, big-120b,
translate-9b ...) is served in every profile: a smaller profile maps the missing roles onto the
models it does have through llama-swap aliases, so the bot code needs no profile switch.
The embedder always runs on CPU outside llama-swap (:5899): under llama-swap it wedged on start.
"""
import os
import sys

IMAGE = 'ghcr.io/mostlygeek/llama-swap:v229-cuda-b9776'
F20 = 'gpt-oss-20b-MXFP4.gguf'
G31 = 'gemma-4-31B-it-Q4_K_S.gguf'
B120 = 'gpt-oss-120b-MXFP4.gguf'
EMB = 'Qwen3-Embedding-8B-Q8_0.gguf'
# names the bot and its agents call (docker-compose.yml + services/*); all must resolve
CHAT_NAMES = ['fast', 'gpt-oss-20b-heretic', 'translate-9b', 'gemma-2-9b-translate', 'agent-cli']
REASONER_NAMES = ['reasoner-31b-b', 'agent-30b']
BIG_NAMES = ['big', 'gpt-oss-120b', 'agent-big', 'smart', 'forensic-xl']


def model(name, gguf, gpus, aliases, ctx=65536, ttl=86400):
    split = ('--split-mode none --main-gpu 0' if len(gpus) == 1
             else '--split-mode layer --tensor-split %s' % ','.join('1' for _ in gpus))  # even split: measured on 120b
    return '\n'.join([
        '  "%s":' % name,
        '    cmd: |',
        '      /app/llama-server',
        '      -m /models/%s' % gguf,
        '      --host 127.0.0.1 --port ${PORT}',
        '      -ngl 99 %s' % split,
        '      -fa auto --jinja',
        '      -c %d --cache-type-k q8_0 --cache-type-v q8_0' % ctx,
        '      --no-webui',
        '    proxy: "http://127.0.0.1:${PORT}"',
        '    env:',
        '      - "CUDA_VISIBLE_DEVICES=%s"' % ','.join(str(g) for g in gpus),
        '    aliases:',
    ] + ['      - "%s"' % a for a in aliases] + ['    ttl: %d' % ttl, ''])


def config(profile, n, min_gb):
    head = ['# GENERATED by installer/gen_llm_stack.py for profile %s (%d GPU, smallest %d GB).' % (profile, n, min_gb),
            '# Re-run install.sh --reconfigure to change; hand edits are overwritten.',
            'healthCheckTimeout: 900', 'startPort: 5840', 'logLevel: info', '', 'models:']
    if profile == 'small':
        body = [model('gpt-small-20b', F20, [0], CHAT_NAMES + ['reasoner-31b'] + REASONER_NAMES + ['big-120b'] + BIG_NAMES)]
        return '\n'.join(head + body)
    # medium/large: chat on card 0, reasoner on the rest (one card if it fits the 31B + 64k ctx)
    rest = list(range(1, n))
    rgpus = rest[:1] if min_gb >= 26 else rest[:2] if len(rest) >= 2 else rest
    big_alias = [] if profile == 'large' else ['big-120b'] + BIG_NAMES
    if len(rgpus) * min_gb < 26:
        # not enough room beside the chat card (e.g. 2 x 20 GB): the reasoner takes every card and
        # also answers the chat names; one model, nothing to swap
        return '\n'.join(head + [model('reasoner-31b', G31, list(range(n)),
                                       ['gpt-small-20b'] + CHAT_NAMES + REASONER_NAMES + big_alias)])
    body = [model('gpt-small-20b', F20, [0], CHAT_NAMES),
            model('reasoner-31b', G31, rgpus, REASONER_NAMES + big_alias)]
    tail = ['matrix:', '  vars:', '    chat: "gpt-small-20b"', '    rea: "reasoner-31b"']
    if profile == 'large':
        body.append(model('big-120b', B120, list(range(n)), BIG_NAMES, ttl=900))
        tail += ['    big: "big-120b"', '  sets:', '    main: "chat & rea"', '    bigset: "big"']
    else:
        tail += ['  sets:', '    main: "chat & rea"']
    return '\n'.join(head + body + tail) + '\n'


def compose(profile, models_dir, router_dir=None):
    gpu = profile not in ('cpu-remote', 'router')
    out = ['# GENERATED by installer/gen_llm_stack.py', 'services:']
    if gpu:
        out += ['  llama-swap:', '    image: %s' % IMAGE, '    container_name: llama-swap', '    network_mode: host',
                '    restart: unless-stopped', '    runtime: nvidia',
                '    environment:', '      NVIDIA_VISIBLE_DEVICES: "all"', '      CUDA_DEVICE_ORDER: "PCI_BUS_ID"',
                '    entrypoint: ["/app/llama-swap"]',
                '    command: ["-config", "/app/config.yaml", "-listen", "0.0.0.0:1234", "-watch-config"]',
                '    healthcheck:', '      test: ["CMD", "curl", "-fs", "http://127.0.0.1:1234/health"]', '      interval: 30s', '      timeout: 5s', '      retries: 3', '      start_period: 180s',
                '    volumes:', '      - ./config.yaml:/app/config.yaml:ro', '      - %s:/models:ro' % models_dir]
    out += ['  embed-cpu:', '    image: %s' % IMAGE, '    container_name: embed-cpu', '    network_mode: host',
            '    restart: unless-stopped', '    environment:', '      NVIDIA_VISIBLE_DEVICES: "void"',
            '    entrypoint: ["/app/llama-server"]',
            '    command: ["-m", "/models/%s", "--host", "0.0.0.0", "--port", "5899", "-ngl", "0", "-t", "%d",'
            ' "--embedding", "--pooling", "last", "-c", "8192", "-ub", "2048", "--no-webui"]' % (EMB, max(2, min(16, os.cpu_count() or 4))),
            '    healthcheck:', '      test: ["CMD", "curl", "-fs", "http://127.0.0.1:5899/health"]', '      interval: 30s', '      timeout: 5s', '      retries: 3', '      start_period: 180s',
                '    volumes:', '      - %s:/models:ro' % models_dir]
    if router_dir:
        # listens on docker0's address only (router.json): it holds API keys, keep it off the LAN
        out += ['  llm-router:', '    image: python:3.12-slim', '    container_name: llm-router', '    network_mode: host',
                '    restart: unless-stopped', '    environment:', '      ROUTER_CONFIG: /config/router.json',
                '    command: ["python3", "-u", "/app/router.py"]',
                '    volumes:', '      - %s:/app:ro' % router_dir, '      - ./router.json:/config/router.json:ro']
    return '\n'.join(out) + '\n'


def main():
    profile, n, min_gb, models_dir, out = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4], sys.argv[5]
    router_dir = sys.argv[6] if len(sys.argv) > 6 and profile == 'router' else None
    os.makedirs(out, exist_ok=True)
    if profile not in ('cpu-remote', 'router'):
        if n < 1 or (profile != 'small' and n < 2):
            sys.exit('profile %s needs %s GPU(s), found %d' % (profile, '1' if profile == 'small' else '2+', n))
        open(os.path.join(out, 'config.yaml'), 'w').write(config(profile, n, min_gb))
    open(os.path.join(out, 'docker-compose.yml'), 'w').write(compose(profile, models_dir, router_dir))
    print('LLM stack for %s written to %s' % (profile, out))


if __name__ == '__main__':
    main()
