# T9 optional modules (sourced by install.sh and dfirctl.sh after lib.sh).
# The list itself is infra/modules.json: the same file tg-i18n reads to hide the buttons of a module that
# is off. MODULES_OFF (state/install_answers.env) = ids separated by spaces; unset/empty = everything on,
# so an install made before T9 keeps every part.
MODULES_JSON="$ROOT/infra/modules.json"

mod_ids()   { python3 -c 'import json,sys;print(" ".join(m["id"] for m in json.load(open(sys.argv[1]))["modules"]))' "$MODULES_JSON"; }
# mod_get ID FIELD -> value (lists joined by spaces)
mod_get()   { python3 -c 'import json,sys
m={x["id"]:x for x in json.load(open(sys.argv[1]))["modules"]}[sys.argv[2]][sys.argv[3]]
print(" ".join(m) if isinstance(m,list) else m)' "$MODULES_JSON" "$1" "$2"; }
mod_on()    { case " ${MODULES_OFF:-} " in *" $1 "*) return 1 ;; *) return 0 ;; esac; }
# services of every switched-off module
mod_off_services() { local m; for m in ${MODULES_OFF:-}; do mod_get "$m" services; done | tr ' ' '\n' | grep -v '^$' || true; }

# sec_modules: numbered list with the size each part needs; the person types the numbers to switch OFF
sec_modules() {
  step modules
  _remember MODULES_OFF
  [ -n "${MODULES_OFF+x}" ] && return 0
  if ! interactive; then MODULES_OFF=""; return 0; fi
  local ids=($(mod_ids)) i id ans off n bad
  while :; do
    t modules_intro; echo
    for i in "${!ids[@]}"; do
      id=${ids[$i]}
      printf '    %s%d)%s %s  %s(%s GB)%s\n' "$C_B" $((i+1)) "$C_0" "$(t "mod_$id")" "$C_G" "$(mod_get "$id" size_gb)" "$C_0"
      printf '       %s\n' "$(t "d_mod_$id")"
    done
    _read ans "  $(t q_modules_off) $(t help_hint): " modules_off
    off=""; bad=""
    for n in ${ans//,/ }; do
      if [[ "$n" =~ ^[0-9]+$ ]] && [ "$n" -ge 1 ] && [ "$n" -le ${#ids[@]} ]; then off+=" ${ids[$((n-1))]}"; else bad+=" $n"; fi
    done
    [ -z "$bad" ] && break
    wmsg unknown_choice "${bad# }"
  done
  MODULES_OFF=$(printf '%s\n' $off | awk 'NF && !s[$0]++' | tr '\n' ' ' | sed 's/ $//')
}

modules_summary() {  # one line for the review screen
  local id on=() off=()
  for id in $(mod_ids); do if mod_on "$id"; then on+=("$id"); else off+=("$id"); fi; done
  printf '%s: %s' "$(t on)" "${on[*]:--}"
  [ ${#off[@]} -gt 0 ] && printf '; %s: %s' "$(t off)" "${off[*]}"
  return 0
}

# Compose override: TUNNEL=url publishes the webhook gate instead of ngrok; a switched-off module's
# services get an inactive profile, so build/pull/up skip them (nothing depends on them, see modules.json).
# An override written by hand (no GENERATED line) is never touched.
write_override() {
  local f="$DESTDIR/docker-compose.override.yml" s svcs
  svcs=$(mod_off_services)
  if [ -f "$f" ] && ! head -1 "$f" | grep -q '^# GENERATED by install.sh'; then wmsg override_own "$f"; return 0; fi
  if [ "${TUNNEL:-ngrok}" != url ] && [ -z "$svcs" ]; then rm -f "$f"; return 0; fi
  {
    echo "# GENERATED by install.sh (TUNNEL=${TUNNEL:-ngrok}, MODULES_OFF=${MODULES_OFF:-}); rewritten on every run"
    echo "services:"
    if [ "${TUNNEL:-ngrok}" = url ]; then
      echo "  # your proxy forwards https://<domain>/ to this host:8099"
      printf '  webhook-gate:\n    ports:\n      - "8099:8099"\n  ngrok:\n    profiles: ["disabled"]\n'
    fi
    for s in $svcs; do printf '  %s:\n    profiles: ["module-off"]\n' "$s"; done
  } > "$f"
}

# apply_modules: .env for tg-i18n + override; a module switched off later: its containers and units go
apply_modules() {
  [ "$DRY_RUN" = 1 ] && { say "DRY_RUN: modules off: ${MODULES_OFF:--}"; return 0; }
  local f="$DESTDIR/.env" s
  if [ -f "$f" ]; then
    if grep -q '^DFIR_MODULES_OFF=' "$f"; then sed -i "s|^DFIR_MODULES_OFF=.*|DFIR_MODULES_OFF=${MODULES_OFF:-}|" "$f"
    else echo "DFIR_MODULES_OFF=${MODULES_OFF:-}" >> "$f"; fi
  fi
  write_override
  # a service named on the command line is handled even with its profile off
  s=$(mod_off_services)
  [ -n "$s" ] && docker compose --project-directory "$DESTDIR" rm -sf $s >/dev/null 2>&1 || true
  if ! mod_on webchat; then
    systemctl disable --now dfir-sandbox-api owui-retention.timer >/dev/null 2>&1 || true
  fi
  # a switched-off module frees its disk: images only it uses (data volumes are kept, switching on again restores)
  local m img
  for m in ${MODULES_OFF:-}; do
    for img in $(mod_get "$m" images); do
      docker image ls -q "$img" | sort -u | xargs -r docker image rm -f >/dev/null 2>&1 || true
    done
  done
  msg modules_applied "${MODULES_OFF:--}"
}
