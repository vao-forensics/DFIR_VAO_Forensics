"""ETAP 6 schema — idempotent init for logs-first provenance tables."""
import logging
import psycopg2
from core.config import PG_DSN

_log = logging.getLogger('app')


def _ensure_v6_tables():
    """Create/migrate all ETAP 6 tables. Safe to call multiple times."""
    try:
        with psycopg2.connect(PG_DSN) as conn:
            conn.autocommit = True
            with conn.cursor() as cur:
                # dfir_case_facts — evidence-backed facts per case
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS dfir_case_facts (
                        id bigserial PRIMARY KEY,
                        case_key text NOT NULL,
                        fact_type text NOT NULL,
                        event_ts timestamptz,
                        title text NOT NULL,
                        description text,
                        source_table text,
                        source_file text,
                        source_ref text,
                        event_id integer,
                        artifact_type text,
                        path text,
                        username text,
                        src_ip text,
                        hash text,
                        confidence real DEFAULT 1.0,
                        status text NOT NULL DEFAULT 'active',
                        validation_status text NOT NULL DEFAULT 'not_checked',
                        validation_reason text,
                        created_at timestamptz NOT NULL DEFAULT now(),
                        updated_at timestamptz NOT NULL DEFAULT now()
                    )
                """)
                cur.execute("CREATE INDEX IF NOT EXISTS idx_case_facts_case ON dfir_case_facts(case_key)")
                cur.execute("CREATE INDEX IF NOT EXISTS idx_case_facts_type ON dfir_case_facts(case_key, fact_type)")
                cur.execute("CREATE INDEX IF NOT EXISTS idx_case_facts_status ON dfir_case_facts(status)")

                # dfir_case_timeline_cache — per-case logs-first timeline
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS dfir_case_timeline_cache (
                        id bigserial PRIMARY KEY,
                        case_key text NOT NULL UNIQUE,
                        timeline_version integer NOT NULL DEFAULT 1,
                        status text NOT NULL DEFAULT 'building',
                        generated_from text NOT NULL DEFAULT 'logs',
                        events_json jsonb,
                        sources_json jsonb,
                        report_validation_json jsonb,
                        model_used text,
                        created_at timestamptz NOT NULL DEFAULT now(),
                        updated_at timestamptz NOT NULL DEFAULT now()
                    )
                """)
                cur.execute("CREATE INDEX IF NOT EXISTS idx_tl_cache_case ON dfir_case_timeline_cache(case_key)")

                # dfir_case_verified_findings — analyst-approved facts per case.
                # This is the durable per-case memory: facts confirmed by operator/operator
                # should be reused by chat/timeline/report prompts instead of being
                # rediscovered/regenerated by the model every time.
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS dfir_case_verified_findings (
                        id bigserial PRIMARY KEY,
                        case_key text NOT NULL,
                        finding_key text NOT NULL,
                        finding_type text NOT NULL DEFAULT 'fact',
                        title text NOT NULL,
                        value text,
                        event_ts timestamptz,
                        evidence_json jsonb,
                        source_kind text NOT NULL DEFAULT 'analyst',
                        approval_status text NOT NULL DEFAULT 'approved',
                        approved_by text,
                        approved_at timestamptz,
                        rejected_at timestamptz,
                        confidence real NOT NULL DEFAULT 1.0,
                        created_at timestamptz NOT NULL DEFAULT now(),
                        updated_at timestamptz NOT NULL DEFAULT now(),
                        UNIQUE(case_key, finding_key)
                    )
                """)
                cur.execute("CREATE INDEX IF NOT EXISTS idx_verified_findings_case ON dfir_case_verified_findings(case_key, approval_status)")
                cur.execute("CREATE INDEX IF NOT EXISTS idx_verified_findings_type ON dfir_case_verified_findings(case_key, finding_type)")

                # dfir_global_artifact_playbooks — search methods only, no case-specific facts
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS dfir_global_artifact_playbooks (
                        id bigserial PRIMARY KEY,
                        intent_name text NOT NULL UNIQUE,
                        question_examples text[],
                        artifact_type text,
                        preferred_tables text[],
                        preferred_event_ids integer[],
                        preferred_registry_paths text[],
                        preferred_source_file_patterns text[],
                        sql_templates jsonb,
                        evidence_requirements jsonb,
                        output_template text,
                        success_count integer NOT NULL DEFAULT 0,
                        fail_count integer NOT NULL DEFAULT 0,
                        status text NOT NULL DEFAULT 'active',
                        created_at timestamptz NOT NULL DEFAULT now(),
                        updated_at timestamptz NOT NULL DEFAULT now()
                    )
                """)
                cur.execute("CREATE INDEX IF NOT EXISTS idx_gap_intent ON dfir_global_artifact_playbooks(intent_name)")

                # dfir_model_routing_audit — audit trail of model routing decisions
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS dfir_model_routing_audit (
                        id bigserial PRIMARY KEY,
                        task_name text NOT NULL,
                        case_key text,
                        chat_id text,
                        model_used text NOT NULL,
                        model_role text NOT NULL DEFAULT 'fast',
                        reason text,
                        escalated_to_strong boolean NOT NULL DEFAULT false,
                        escalation_reason text,
                        input_tokens integer,
                        output_tokens integer,
                        duration_ms integer,
                        created_at timestamptz NOT NULL DEFAULT now()
                    )
                """)
                cur.execute("CREATE INDEX IF NOT EXISTS idx_mra_task ON dfir_model_routing_audit(task_name)")
                cur.execute("CREATE INDEX IF NOT EXISTS idx_mra_case ON dfir_model_routing_audit(case_key)")
                cur.execute("CREATE INDEX IF NOT EXISTS idx_mra_created ON dfir_model_routing_audit(created_at DESC)")

                # Migrate dfir_qa_answers — add provenance columns
                for col, defn in [
                    ('validation_status', "text NOT NULL DEFAULT 'not_checked'"),
                    ('validation_reason', 'text'),
                    ('not_in_report', 'boolean NOT NULL DEFAULT false'),
                    ('conflict_with_report', 'boolean NOT NULL DEFAULT false'),
                    ('source_ref', 'text'),
                    ('model_used', 'text'),
                    ('model_role', 'text'),
                ]:
                    try:
                        cur.execute(f"ALTER TABLE dfir_qa_answers ADD COLUMN IF NOT EXISTS {col} {defn}")
                    except Exception:
                        pass

        _log.info('[schema_v6] all ETAP 6 tables OK')
    except Exception as e:
        _log.error(f'[schema_v6] init error: {e}')
